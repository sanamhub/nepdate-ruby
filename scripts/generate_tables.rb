# frozen_string_literal: true

# Compiles shared/data/calendar/bs-calendar.json into the core package's constant table
# (spec/ALGORITHM.md sections 1 and 2). The JSON is read only here; the gem never reads a data
# file at runtime.
#
#   ruby scripts/generate_tables.rb           regenerate
#   ruby scripts/generate_tables.rb --check   fail if the committed file would change

require "json"

ROOT = File.expand_path("..", __dir__)
CALENDAR_PATH = File.join(ROOT, "shared/data/calendar/bs-calendar.json")
OUT_PATH = File.join(ROOT, "packages/nepdate/lib/nepdate/calendar_table.rb")

def fail_with(message)
  warn message
  exit 1
end

def read_calendar
  JSON.parse(File.read(CALENDAR_PATH, encoding: "UTF-8"))
rescue Errno::ENOENT, JSON::ParserError => e
  fail_with("cannot read #{CALENDAR_PATH}: #{e.message}")
end

def generate
  calendar = read_calendar
  min_year = calendar.fetch("min_year")
  max_year = calendar.fetch("max_year")
  lengths = calendar.fetch("month_lengths")
  years = max_year - min_year + 1

  fail_with("month_lengths must hold #{years} years") unless lengths.size == years

  packed = []
  year_start = [0]
  month_start = []
  cursor = 0
  (min_year..max_year).each do |year|
    months = lengths.fetch(year.to_s)
    fail_with("year #{year} must have 12 months") unless months.size == 12
    months.each do |length|
      fail_with("month length #{length} in #{year} is outside 29..32") unless (29..32).cover?(length)
    end
    bits = 0
    months.each_with_index { |length, index| bits |= (length - 29) << (2 * index) }
    packed << bits
    months.each do |length|
      month_start << cursor
      cursor += length
    end
    year_start << cursor
  end

  month_start << cursor
  total_days = year_start.last
  max_serial = total_days - 1

  # A bucket is 32 days, one more than the longest month, so a serial is at most two month
  # starts past the bucket's own month.
  bucket = []
  bucket_start = 0
  month_index = 0
  while bucket_start <= max_serial
    month_index += 1 while month_index + 1 < month_start.length && month_start[month_index + 1] <= bucket_start
    bucket << month_index
    bucket_start += 32
  end

  packed_lines = packed.each_slice(12).map { |slice| "      #{slice.join(", ")}," }
  start_lines = year_start.each_slice(12).map { |slice| "      #{slice.join(", ")}," }
  month_lines = month_start.each_slice(12).map { |slice| "      #{slice.join(", ")}," }
  bucket_lines = bucket.each_slice(15).map { |slice| "      #{slice.join(", ")}," }

  <<~RUBY
    # frozen_string_literal: true

    # DO NOT EDIT. Generated by scripts/generate_tables.rb from
    # shared/data/calendar/bs-calendar.json, which comes from RajuPrasai/NepDate. The layout is
    # spec/ALGORITHM.md sections 1 and 2.

    module NepDate
      # The BS month lengths and year starts, packed exactly as ALGORITHM.md defines them.
      # @api private
      module CalendarTable
        MIN_YEAR = #{min_year}
        MAX_YEAR = #{max_year}
        YEARS = #{years}
        TOTAL_DAYS = #{total_days}
        MAX_SERIAL = #{max_serial}
        EPOCH_UNIX_DAYS = -45920
        EPOCH_WEEKDAY = 4
        # The Julian day number of serial 0, so a ::Date can convert without splitting its fields.
        JULIAN_EPOCH = 2394668

        # Twelve two-bit values per year: month length minus 29, month 1 in the lowest bits.
        PACKED = [
    #{packed_lines.join("\n")}
        ].freeze

        # The serial of 1 Baishakh for every year, plus the serial one day after the last year.
        YEAR_START = [
    #{start_lines.join("\n")}
        ].freeze

        # The serial of the first day of every month, plus the serial one day after the last
        # month. Month index 0 is 1901-01 and index 3587 is 2199-12.
        MONTH_START = [
    #{month_lines.join("\n")}
        ].freeze

        # For each 32-day bucket, the month index containing its first day. A lookup checks at
        # most two following month starts, because no month is longer than 32 days.
        BUCKET = [
    #{bucket_lines.join("\n")}
        ].freeze
      end
    end
  RUBY
end

generated = generate

if ARGV.include?("--check")
  current = File.exist?(OUT_PATH) ? File.read(OUT_PATH, encoding: "UTF-8") : nil
  if current != generated
    warn "packages/nepdate/lib/nepdate/calendar_table.rb is out of date; run: ruby scripts/generate_tables.rb"
    exit 1
  end
  puts "packages/nepdate/lib/nepdate/calendar_table.rb matches shared/data/calendar/bs-calendar.json"
else
  File.write(OUT_PATH, generated, encoding: "UTF-8")
  puts "wrote packages/nepdate/lib/nepdate/calendar_table.rb (299 years, 109212 days)"
end
